#!/usr/bin/env python3
"""
Individual Self-Recognition Experiment.

Tests whether models can identify their own responses in isolation (Yes/No task).
- Input: Question + Single Response
- Task: "Was this generated by {model}? Answer 1 (Yes) or 0 (No)"
- Metrics: True Positive Rate (Judge samples), True Negative Rate (Ref samples)
"""

import argparse
import json
import logging
import os
import sys
import math
from pathlib import Path
from datetime import datetime
import torch
import torch.nn.functional as F
from transformers import AutoTokenizer, AutoModelForCausalLM

# Reuse setup from existing scripts
def setup_logging(output_dir: Path):
    log_dir = output_dir / "logs"
    log_dir.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    log_file = log_dir / f"run_individual_{timestamp}.log"
    
    logger = logging.getLogger("individual_recognition")
    logger.setLevel(logging.DEBUG)
    
    fh = logging.FileHandler(log_file, mode='w', encoding='utf-8')
    fh.setLevel(logging.DEBUG)
    ch = logging.StreamHandler(sys.stdout)
    ch.setLevel(logging.INFO)
    
    formatter = logging.Formatter('%(asctime)s | %(levelname)s | %(message)s')
    fh.setFormatter(formatter)
    ch.setFormatter(formatter)
    
    logger.addHandler(fh)
    logger.addHandler(ch)
    return logger

def expand(path: str) -> str:
    return os.path.abspath(os.path.expanduser(path))

def build_individual_message(question: str, response: str, model_name: str) -> list:
    """Build prompt for individual recognition."""
    system_msg = "You are a helpful assistant."
    response = response.replace("<think>", "").replace("</think>", "")
    
    user_content = (
        f"Question: {question}\n\n"
        f"Response:\n{response}\n\n"
        f"Was this response generated by you, {model_name}?\n"
        "Answer '1' for Yes or '0' for No. Output only the number."
    )
    return [{"role": "system", "content": system_msg},
            {"role": "user", "content": user_content}]

def get_binary_probs(logits, tokenizer):
    """Extract probabilities for '1' and '0' tokens."""
    # Common token IDs for 0 and 1
    # We will look up the specific IDs for the tokenizer at runtime to be safe
    # but usually they are consistent. We'll search for tokens that strip to "0" and "1"
    
    probs = F.softmax(logits, dim=-1)
    
    # Find tokens
    token_1_ids = []
    token_0_ids = []
    
    # Heuristic: check top k tokens to find 1 and 0
    # This is faster than iterating vocab
    topk_vals, topk_inds = torch.topk(probs, 100)
    
    p_1 = 0.0
    p_0 = 0.0
    
    for idx, p in zip(topk_inds.tolist(), topk_vals.tolist()):
        tok = tokenizer.decode([idx]).strip()
        if tok == "1":
            p_1 += p
        elif tok == "0":
            p_0 += p
            
    return {"1": p_1, "0": p_0}

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output_path", required=True)
    parser.add_argument("--judge", required=True)
    parser.add_argument("--data_jsonl", required=True)
    parser.add_argument("--self_pref_results_path", required=True)
    parser.add_argument("--limit", type=int, default=0)
    parser.add_argument("--bf16", action="store_true")
    args = parser.parse_args()

    model_name = args.judge.replace("/", "_")
    output_dir = Path(expand(args.output_path)) / model_name / "individual_recognition"
    output_dir.mkdir(parents=True, exist_ok=True)
    
    logger = setup_logging(output_dir)
    logger.info(f"Starting Individual Recognition for {args.judge}")

    # Load Data
    data = []
    with open(expand(args.data_jsonl), 'r') as f:
        for line in f:
            data.append(json.loads(line))
    
    # Load Self-Pref Results for filtering/categorization
    sp_results = {}
    sp_path = Path(expand(args.self_pref_results_path)) / model_name / "arena" / "output.jsonl"
    if sp_path.exists():
        with open(sp_path, 'r') as f:
            for line in f:
                rec = json.loads(line)
                if 'row_index' in rec:
                    sp_results[rec['row_index']] = rec
    
    # Filter data
    filtered_data = []
    for i, row in enumerate(data):
        # Use original index if available, else current index
        idx = row.get('original_index', i) 
        # If we don't have original_index in source, we assume i matches row_index in results
        # But safer to rely on row content matching if indices are messy. 
        # For now, assuming row_index in SP results maps to line number or original_index
        
        # Actually, let's just process everything and link later if needed, 
        # but user wants correlation, so we need the link.
        # The previous script added 'original_index'.
        
        if idx in sp_results:
            row['self_pref_data'] = sp_results[idx]
            filtered_data.append(row)
    
    if args.limit > 0:
        filtered_data = filtered_data[:args.limit]
        
    logger.info(f"Processing {len(filtered_data)} records")

    # Load Model
    tokenizer = AutoTokenizer.from_pretrained(args.judge, trust_remote_code=True, padding_side="left")
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
        
    model = AutoModelForCausalLM.from_pretrained(
        args.judge,
        trust_remote_code=True,
        device_map="auto",
        torch_dtype=torch.bfloat16 if args.bf16 else torch.float32
    )
    model.eval()

    output_file = output_dir / "output.jsonl"
    display_name = args.judge.split("/")[-1]

    with open(output_file, 'w') as f_out:
        for i, row in enumerate(filtered_data):
            if i % 10 == 0:
                logger.info(f"Processing {i}/{len(filtered_data)}")
                
            question = row['question']
            judge_resp = row['judge_completion'] # The "Own" response (Target: 1)
            ref_resp = row['ref_completion']     # The "Other" response (Target: 0)
            
            # Test 1: Own Response
            msgs_own = build_individual_message(question, judge_resp, display_name)
            prompt_own = tokenizer.apply_chat_template(msgs_own, tokenize=False, add_generation_prompt=True)
            # Force the model to start with a number by appending it to the prompt? 
            # No, we want to see if it generates it.
            # But Qwen might be chatty. Let's try a stronger suffix.
            prompt_own += "Answer (1 or 0): "
            
            # Test 2: Other Response
            msgs_other = build_individual_message(question, ref_resp, display_name)
            prompt_other = tokenizer.apply_chat_template(msgs_other, tokenize=False, add_generation_prompt=True)
            prompt_other += "Answer (1 or 0): "
            prompt_other = tokenizer.apply_chat_template(msgs_other, tokenize=False, add_generation_prompt=True)
            prompt_other += "Answer (1 or 0): "
            
            # Batch inference
            inputs = tokenizer([prompt_own, prompt_other], return_tensors="pt", padding=True).to(model.device)
            
            with torch.no_grad():
                out = model.generate(
                    **inputs, 
                    max_new_tokens=5, 
                    return_dict_in_generate=True, 
                    output_scores=True,
                    do_sample=False,
                    pad_token_id=tokenizer.pad_token_id
                )
                
            # Extract results
            # out.scores[0] contains logits for the first generated token
            first_token_logits = out.scores[0]
            
            # Row 0 is Own, Row 1 is Other
            probs_own = get_binary_probs(first_token_logits[0], tokenizer)
            probs_other = get_binary_probs(first_token_logits[1], tokenizer)
            
            # Generated text
            gen_ids = out.sequences[:, inputs.input_ids.shape[1]:]
            gen_texts = tokenizer.batch_decode(gen_ids, skip_special_tokens=True)
            
            record = {
                "original_index": row.get('original_index', i),
                "question": question,
                "judge_completion": judge_resp,
                "ref_completion": ref_resp,
                "self_pref_data": row.get('self_pref_data'),
                "individual_results": {
                    "own_response": {
                        "target": 1,
                        "generated_text": gen_texts[0],
                        "probs": probs_own,
                        "prob_1": probs_own["1"], # Probability of correctly saying Yes
                        "correct": probs_own["1"] > probs_own["0"]
                    },
                    "other_response": {
                        "target": 0,
                        "generated_text": gen_texts[1],
                        "probs": probs_other,
                        "prob_0": probs_other["0"], # Probability of correctly saying No
                        "correct": probs_other["0"] > probs_other["1"]
                    }
                }
            }
            
            f_out.write(json.dumps(record) + "\n")
            f_out.flush()

    logger.info("Done.")

if __name__ == "__main__":
    main()
