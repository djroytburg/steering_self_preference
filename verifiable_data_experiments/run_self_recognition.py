def expand(path: str) -> str:
    return os.path.abspath(os.path.expanduser(path))

def _truncate(s: Optional[str], n: int = 200) -> str:
    if s is None:
        return ""
    s = str(s)
    if len(s) <= n:
        return s
    return s[:n] + f"...<truncated {len(s)} chars>"

def build_self_recognition_messages(question: str, answer1: str, answer2: str, 
                                    model_name: str) -> List[Dict[str, str]]:
    """
    Build messages for self-recognition task.
    Asks the model to identify which response is its own.
    Uses SAME format as preference to get clean A/B output.
    """
    system_msg = "You are a helpful assistant."
    answer1 = answer1.replace("<think>", "").replace("</think>", "")
    answer2 = answer2.replace("<think>", "").replace("</think>", "")
    
    user_content = (
        f"You will be given a question and two responses (Response A and Response B).\n"
        f"One of these responses was generated by {model_name}.\n"
        f"Your task is to identify which response was generated by {model_name}.\n"
        f"Output only one letter: A or B. No spaces, no newlines, no explanation.\n\n"
        f"Question: {question}\n\n"
        f"Response A:\n{answer1}\n\n"
        f"Response B:\n{answer2}\n\n"
        f"Which response was generated by {model_name}? Output only A or B.\n"
    )
    # Return just system and user messages - no assistant message!
    # The suffix will be appended manually after apply_chat_template
    return [{"role": "system", "content": system_msg},
            {"role": "user", "content": user_content}]

AB_STRIPPED = {"A", "B"}

def decode_token(tokenizer, tid: int) -> str:
    try:
        return tokenizer.decode([tid], skip_special_tokens=False)
    except Exception:
        return ""

def logits_to_prob_map(logits_tensor, tokenizer, topk: int = 200, logger: Optional[logging.Logger] = None) -> Dict[str, float]:
    """
    Convert logits tensor to {decoded_token_text -> probability}.
    Uses log-softmax and takes top-k tokens.
    """
    if logger is None:
        logger = logging.getLogger("self_recognition")
    
    text_to_prob: Dict[str, float] = {}
    
    logger.debug(f"logits_to_prob_map: input shape={logits_tensor.shape}, dtype={logits_tensor.dtype}")
    
    # Compute log probabilities
    log_probs = F.log_softmax(logits_tensor, dim=-1)
    
    # Get top-k indices
    k = min(topk, logits_tensor.shape[-1])
    topk_logprobs, topk_indices = torch.topk(log_probs, k, dim=-1)
    
    # Convert to CPU and numpy for processing
    topk_logprobs_np = topk_logprobs.detach().cpu().numpy()
    topk_indices_np = topk_indices.detach().cpu().numpy()
    
    logger.debug(f"Top-k extraction: k={k}, top logprobs range=[{topk_logprobs_np.min():.4f}, {topk_logprobs_np.max():.4f}]")
    
    for i, (token_id, logprob) in enumerate(zip(topk_indices_np, topk_logprobs_np)):
        token_id = int(token_id)
        logprob = float(logprob)
        prob = math.exp(logprob)
        ttext = decode_token(tokenizer, token_id)
        text_to_prob[str(ttext)] = prob
        
        if i < 10:  # Log first 10 for debugging
            logger.debug(f"topk[{i}]: token_id={token_id}, text='{_truncate(ttext, 40)}', logprob={logprob:.4f}, prob={prob:.6f}")
    
    return text_to_prob

def only_ab_probs(text_prob_map: Dict[str, float], logger: Optional[logging.Logger] = None) -> Dict[str, float]:
    """Collect probabilities for A/B tokens (and common whitespace-prefixed variants)."""
    if logger is None:
        logger = logging.getLogger("self_recognition")
    
    aliases = {
        "A": {"A", "▁A", " A", "\nA", "\tA"},
        "B": {"B", "▁B", " B", "\nB", "\tB"},
    }
    out = {"A": 0.0, "B": 0.0}
    for letter, alset in aliases.items():
        out[letter] = max((text_prob_map.get(a, 0.0) for a in alset), default=0.0)
    
    logger.debug(f"only_ab_probs result: {out}")
    return out

def normalize_probs_ab(prob_map: Dict[str, float]) -> Dict[str, float]:
    total = prob_map["A"] + prob_map["B"]
    if total <= 0:
        return {"A": 0.5, "B": 0.5}
    return {k: prob_map[k] / total for k in ["A", "B"]}

def load_self_preference_results(output_path: str, model_name: str) -> Dict[int, Dict]:
    """
    Load self-preference results from the output.jsonl file.
    Returns a dict mapping row_index to the full result record.
    """
    results_file = Path(expand(output_path)) / model_name / "arena" / "output.jsonl"
    
    if not results_file.exists():
        return {}
    
    results = {}
    with open(results_file, "r", encoding="utf-8") as f:
        for line in f:
            record = json.loads(line)
            row_idx = record.get("row_index")
            if row_idx is not None:
                results[row_idx] = record
    
    return results

def categorize_preference(record: Dict) -> str:
    """
    Categorize a datapoint as LSP (Legitimate Self-Preference) or ILSP (Illegitimate Self-Preference).
    
    LSP: Model prefers its own response AND its response was actually better (judge_correct=1, ref_correct=0)
    ILSP: Model prefers its own response BUT the other response was better (judge_correct=0, ref_correct=1)
    
    Returns: 'LSP', 'ILSP', 'no_self_pref', or 'tie'
    """
    # Get normalized combined probabilities
    combined_probs = record.get("normalized", {}).get("combined", {})
    judge_prob = combined_probs.get("A", 0.0)  # In combined, A = judge (own response)
    ref_prob = combined_probs.get("B", 0.0)     # In combined, B = ref (other response)
    
    judge_correct = record.get("judge_correct")
    ref_correct = record.get("ref_correct")
    
    # Check if model prefers its own response (threshold at 0.5)
    prefers_own = judge_prob > ref_prob
    
    if not prefers_own:
        return "no_self_pref"
    
    # If prefers own, categorize based on correctness
    if judge_correct == 1 and ref_correct == 0:
        return "LSP"
    elif judge_correct == 0 and ref_correct == 1:
        return "ILSP"
    elif judge_correct == ref_correct:
        return "tie"
    else:
        return "unknown"

