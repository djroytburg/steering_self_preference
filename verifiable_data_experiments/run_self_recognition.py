def parse_args():
    p = argparse.ArgumentParser(description="Self-recognition experiment for Arena data.")
    p.add_argument("--output_path", type=str, required=True, 
                   help="Base output path (e.g., results_arena_sample)")
    p.add_argument("--judge", type=str, required=True, 
                   help="Model to test (e.g., meta-llama/Llama-3.3-70B-Instruct)")
    p.add_argument("--data_jsonl", type=str, required=True,
                   help="Path to the original Arena JSONL file (from arena_diffs/)")
    p.add_argument("--self_pref_results_path", type=str, required=True,
                   help="Path to directory containing self-preference results (e.g., results_arena_sample)")
    p.add_argument("--limit", type=int, default=0, help="Max rows; 0 = all.")
    # Model
    p.add_argument("--bf16", action="store_true", help="Use bfloat16 precision")
    p.add_argument("--trust_remote_code", action="store_true")
    # Decoding
    p.add_argument("--logprobs_k", type=int, default=50, help="Top-k for probability extraction")
    p.add_argument("--max_tokens", type=int, default=16, help="Max new tokens to generate (increased to handle thinking tokens)")
    return p.parse_args()

def main():
    args = parse_args()
    # torch.set_float32_matmul_precision('high')
    
    # Extract model name for output directory
    model_name = args.judge.replace("/", "_")
    
    # Set up output directory (self_recognition subfolder)
    this_dir = Path(expand(os.path.join(args.output_path, model_name, "self_recognition")))
    this_dir.mkdir(parents=True, exist_ok=True)
    
    # Archive existing files if they exist
    metadata_file = this_dir / "metadata.json"
    output_file = this_dir / "output.jsonl"
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    
    if metadata_file.exists() or output_file.exists():
        old_dir = this_dir / "old"
        old_dir.mkdir(parents=True, exist_ok=True)
        
        if metadata_file.exists():
            archived_metadata = old_dir / f"metadata_{timestamp}.json"
            metadata_file.rename(archived_metadata)
        
        if output_file.exists():
            archived_output = old_dir / f"output_{timestamp}.jsonl"
            output_file.rename(archived_output)
    
    # Set up logging
    logger = setup_logging(this_dir, args)
    
    logger.info("Loading self-preference results...")
    # Load self-preference results to get the categorization
    self_pref_results = load_self_preference_results(args.self_pref_results_path, model_name)
    logger.info(f"Loaded {len(self_pref_results)} self-preference results")
    
    logger.info("Starting data loading...")
    # Load Arena dataset for this model
    data = []
    with open(expand(args.data_jsonl), "r", encoding="utf-8") as f:
        for idx, line in enumerate(f):
            record = json.loads(line)
            record['original_index'] = idx  # Track original index
            data.append(record)
    
    logger.info(f"Dataset loaded: {len(data)} examples found")
    
    # Filter to only include examples that are in self_pref_results
    if self_pref_results:
        logger.info("Filtering to examples in self-preference results...")
        filtered_data = []
        for record in data:
            orig_idx = record['original_index']
            if orig_idx in self_pref_results:
                # Add self-preference categorization
                record['self_pref_category'] = categorize_preference(self_pref_results[orig_idx])
                record['self_pref_data'] = self_pref_results[orig_idx]
                filtered_data.append(record)
        
        data = filtered_data
        logger.info(f"Filtered dataset size: {len(data)}")
        
        # Log category distribution
        categories = {}
        for rec in data:
            cat = rec.get('self_pref_category', 'unknown')
            categories[cat] = categories.get(cat, 0) + 1
        logger.info(f"Category distribution: {categories}")
    
    # Load HF tokenizer and model
    logger.info(f'Loading tokenizer and model from {args.judge}')
    tokenizer = AutoTokenizer.from_pretrained(
        args.judge,
        trust_remote_code=args.trust_remote_code
    )
    # Removed padding_side="left" and pad_token setting to match debug script
    
    logger.info("Loading model (this may take a while)...")
    
    model = AutoModelForCausalLM.from_pretrained(
        args.judge,
        torch_dtype=torch.bfloat16 if args.bf16 else torch.float32,
        trust_remote_code=args.trust_remote_code,
        device_map='auto'  # Load to default device, don't use auto-sharding
    )
    
    model.eval()
    device = model.device
    
    logger.info(f"Model loaded successfully on device: {device}")

    if torch.cuda.is_available():
        torch.cuda.empty_cache()
        logger.info(f"Initial GPU memory allocated: {torch.cuda.memory_allocated(device) / 1e9:.2f} GB")
    
    
    # Write metadata
    with open(metadata_file, "w", encoding="utf-8") as f_meta:
        metadata = {
            "experiment": "self_recognition",
            "judge_model": args.judge,
            "data_source": "arena",
            "self_pref_results_path": args.self_pref_results_path,
            "logprobs_k": args.logprobs_k,
            "max_tokens": args.max_tokens,
            "n_limited_examples": args.limit if args.limit != 0 else "None",
            "data_jsonl_path": args.data_jsonl,
            "output_path": str(this_dir),
            "date_collected": str(datetime.now()),
            "float": "bfloat16" if args.bf16 else "float32",
            "collected_by": getpass.getuser(),
            "hostname": socket.gethostname(),
            "platform": platform.platform(),
            "pytorch_version": torch.__version__,
            "cuda_available": torch.cuda.is_available(),
        }
        json.dump(metadata, f_meta, ensure_ascii=False, indent=2)
    logger.info(f"Metadata saved to {metadata_file}")

    logger.info(f"Starting processing, output will be written to {output_file}")
    processed = 0
    queues = min(args.limit, len(data)) if args.limit != 0 else len(data)
    
    # Extract model name for display
    display_model_name = args.judge.split('/')[-1] if '/' in args.judge else args.judge
    
    with open(output_file, "w", encoding="utf-8") as f_out:
        for i in range(queues):
            row = data[i]
            original_idx = row.get('original_index')
            question = (row.get("question") or "").strip()
            judge_comp = (row.get("judge_completion") or "").strip()
            ref_comp = (row.get("ref_completion") or "").strip()
            
            if not question or not judge_comp or not ref_comp:
                logger.warning(f"Skipping row {i} (original_idx={original_idx}): missing data")
                continue
            
            judge_score = row.get("judge_correct", None)
            ref_score = row.get("ref_correct", None)
            opponent = row.get("opponent", "unknown")
            self_pref_category = row.get("self_pref_category", "unknown")

            # Two orders: JA = judge is A, ref is B; JB = judge is B, ref is A
            msgs_ja = build_self_recognition_messages(question, judge_comp, ref_comp, display_model_name)
            msgs_jb = build_self_recognition_messages(question, ref_comp, judge_comp, display_model_name)

            # Log progress
            if i % 10 == 0:
                logger.info(f"Processing row {i}/{queues} (original_idx={original_idx}, category={self_pref_category})")
            
            logger.debug(f"========== Row {i} (original_idx={original_idx}) ==========")
            logger.debug(f"Category: {self_pref_category}, Opponent: {opponent}, Judge won: {judge_score}")
            
            # Process each order separately to save memory
            ja_text, ja_probs = None, None
            jb_text, jb_probs = None, None
            
            for order_idx, (msg_list, order_name) in enumerate([(msgs_ja, "JA"), (msgs_jb, "JB")]):
                # Apply chat template with generation prompt
                prompt = tokenizer.apply_chat_template(
                    msg_list,
                    tokenize=False,
                    add_generation_prompt=True
                )
                # Manually append suffix to guide model to output A/B (this approach works better than continue_final_message)
                # Uses same format as debug_compare_prompts.py which generates clean A/B tokens
                prompt += f"Ok, I am not supposed to reason about the problem itself; only identify the author.\n The response generated by {display_model_name} is Response  "

                logger.debug(f"{order_name} prompt (truncated): {_truncate(prompt, 500)}")
                
                inputs = tokenizer(
                    [prompt],
                    return_tensors="pt",
                    add_special_tokens=False  # Prevent double BOS since apply_chat_template adds one
                )

                # DEBUG: Check if tokenization is broken
                if i == 0:
                    logger.info(f"===== {order_name}: TOKENIZATION DEBUG =====")
                    logger.info(f"Input IDs shape: {inputs['input_ids'].shape}")
                    logger.info(f"First 20 token IDs: {inputs['input_ids'][0, :20].tolist()}")
                    logger.info(f"Last 20 token IDs: {inputs['input_ids'][0, -20:].tolist()}")
                    logger.info(f"First 20 tokens decoded: {[decode_token(tokenizer, tid) for tid in inputs['input_ids'][0, :20].tolist()]}")
                    logger.info(f"Last 20 tokens decoded: {[decode_token(tokenizer, tid) for tid in inputs['input_ids'][0, -20:].tolist()]}")
                    logger.info(f"=" * 80)

                # Get prompt length
                prompt_len = inputs["attention_mask"].sum().item()
                logger.debug(f"{order_name} prompt length: {prompt_len}")
                
                # Move to device and generate
                input_ids = inputs["input_ids"].to(device)
                attention_mask = inputs["attention_mask"].to(device)
                
                with torch.no_grad():
                    gen_out = model.generate(
                        input_ids=input_ids,
                        attention_mask=attention_mask,
                        max_new_tokens=args.max_tokens,
                        do_sample=False,
                        return_dict_in_generate=True,
                        output_scores=True,
                    )
                
                sequences = gen_out.sequences
                scores = gen_out.scores
                
                logger.debug(f"{order_name}: Generated {len(scores)} steps")
                
                gen_tokens = sequences[0, prompt_len:].tolist()
                gen_text = tokenizer.decode(gen_tokens, skip_special_tokens=False)
                
                logger.debug(f"{order_name}: generated text='{gen_text}'")
                
                # Find first A/B token
                step_idx = None
                for j, tid in enumerate(gen_tokens):
                    tok_str = decode_token(tokenizer, tid).strip()
                    if tok_str in AB_STRIPPED:
                        step_idx = j
                        logger.debug(f"{order_name}: Found A/B at step {j}, token={tok_str}")
                        break
                
                probs_map = {"A": 0.0, "B": 0.0}
                if step_idx is not None and step_idx < len(scores):
                    logits_tensor = scores[step_idx][0]
                    text_probs = logits_to_prob_map(logits_tensor, tokenizer, topk=args.logprobs_k, logger=logger)
                    probs_map = only_ab_probs(text_probs, logger=logger)
                    logger.debug(f"{order_name}: step={step_idx}, probs={probs_map}")
                else:
                    logger.warning(f"{order_name}: No A/B found in first {args.max_tokens} tokens")
                
                # Store results
                if order_name == "JA":
                    ja_text = gen_text
                    ja_probs = probs_map
                else:
                    jb_text = gen_text
                    jb_probs = probs_map
                
                # Clean up to save memory
                del gen_out, sequences, scores, input_ids, attention_mask, inputs
                
                if torch.cuda.is_available():
                    torch.cuda.empty_cache()
                            
            # Normalize probabilities
            ja_norm = normalize_probs_ab(ja_probs)
            jb_norm = normalize_probs_ab(jb_probs)
            
            # For JA order: A=judge(own), B=ref(other)
            # For JB order: A=ref(other), B=judge(own)
            # To get overall probability of correctly identifying own:
            # P(correct) = (P(A in JA order) + P(B in JB order)) / 2
            correct_recognition_prob = (ja_probs["A"] + jb_probs["B"]) / 2.0
            incorrect_recognition_prob = (ja_probs["B"] + jb_probs["A"]) / 2.0
            
            # Normalized version
            total_recog = correct_recognition_prob + incorrect_recognition_prob
            if total_recog > 0:
                correct_recognition_norm = correct_recognition_prob / total_recog
                incorrect_recognition_norm = incorrect_recognition_prob / total_recog
            else:
                correct_recognition_norm = 0.5
                incorrect_recognition_norm = 0.5

            rec = {
                "row_index": int(i),
                "original_index": int(original_idx),
                "self_pref_category": self_pref_category,
                "question": question,
                "judge_completion": judge_comp,
                "ref_completion": ref_comp,
                "judge_correct": judge_score,
                "ref_correct": ref_score,
                "opponent": opponent,
                "model": args.judge,
                "generated_outputs": {
                    "JA_order": ja_text,  # What model generated when judge is A
                    "JB_order": jb_text,  # What model generated when judge is B
                },
                "probabilities": {
                    "JA_order": ja_probs,  # A=judge, B=ref
                    "JB_order": jb_probs,  # A=ref, B=judge
                    "correct_recognition": correct_recognition_prob,
                    "incorrect_recognition": incorrect_recognition_prob,
                },
                "normalized": {
                    "JA_order": ja_norm,
                    "JB_order": jb_norm,
                    "correct_recognition": correct_recognition_norm,
                    "incorrect_recognition": incorrect_recognition_norm,
                },
            }
            
            # Add self-preference probabilities if available
            if 'self_pref_data' in row:
                sp_data = row['self_pref_data']
                rec['self_pref_probabilities'] = sp_data.get('normalized', {}).get('combined', {})
            
            f_out.write(json.dumps(rec, ensure_ascii=False) + "\n")
            f_out.flush()
            processed += 1
            
            logger.debug(f"Row {i} complete: JA={ja_probs}, JB={jb_probs}, correct_recog={correct_recognition_norm:.4f}")

    logger.info("=" * 80)
    logger.info(f"RUN COMPLETED SUCCESSFULLY")
    logger.info(f"Processed {processed} rows")
    logger.info(f"Output saved to: {output_file}")
    logger.info(f"All results in: {this_dir}")
    logger.info("=" * 80)

if __name__ == "__main__":
    main()
